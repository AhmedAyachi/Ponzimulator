

pub fn help(_args:&Vec<String>){
    println!("Available commands:");
    println!("chasin: cashs a person in.");
    println!("cashout: cashs a person out.");
    println!("list: lists the registered accounts.");
    println!("select: logs account details.");
    println!("start: starts the simulation daemon.");
    println!("stop: stops the simulation daemon.");
    println!("status: logs the current simulation status.");
    println!("exit: exits the interactive terminal interface.");
    println!("clear: clears the interactive terminal interface.");
    println!("help: prints the current help log.");
}
